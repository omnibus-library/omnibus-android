package com.omnibus.omnibus.data.library

/** A [Book] with every optional field empty, for tests that only care about a few fields. */
fun testBook(
    id: Long,
    title: String? = "Book $id",
    creators: List<Creator> = listOf(Creator("Author $id", null, null, null)),
    formats: List<String> = listOf("epub"),
    uniqueIdentifier: String? = "uuid-$id",
    filename: String = "book-$id.epub",
    series: String? = null,
    seriesIndex: String? = null,
    accent: String? = null,
    coverUrl: String? = null,
    bookFiles: List<BookFile> = emptyList(),
    description: String? = null,
    genres: List<String> = emptyList(),
    subjects: List<String> = emptyList(),
    publisher: String? = null,
    publishedDate: String? = null,
    language: String? = null,
    isbn13: String? = null,
    seriesId: Long? = null,
    isWishlisted: Boolean = false,
    wishlistSource: String? = null,
): Book = Book(
    id = id,
    uniqueIdentifier = uniqueIdentifier,
    filename = filename,
    title = title,
    creators = creators,
    coverUrl = coverUrl,
    accent = accent,
    formats = formats,
    series = series,
    seriesIndex = seriesIndex,
    hasPhysical = false,
    addedAt = null,
    lastInteractedAt = null,
    bookFiles = bookFiles,
    description = description,
    genres = genres,
    subjects = subjects,
    publisher = publisher,
    publishedDate = publishedDate,
    language = language,
    isbn13 = isbn13,
    seriesId = seriesId,
    isWishlisted = isWishlisted,
    wishlistSource = wishlistSource,
)
