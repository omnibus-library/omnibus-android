package com.omnibus.omnibus.feature.requests

/**
 * The strings the request rules use, so the functions that build a line stay pure. The defaults are the web's English;
 * screens fill it from string resources. Placeholders arrive as function arguments.
 */
data class RequestWording(
    // A request's state
    val looking: String = "Looking",
    val lookingNote: String = "Searching for versions of this book.",
    val choose: String = "Choose a version",
    val chosen: String = "Version chosen",
    val chosenNote: String = "We’ll fetch it next.",
    val onItsWay: String = "On its way",
    val onItsWayNote: String = "Downloading, then adding it to the library.",
    val readyToRead: String = "Ready to read",
    val readyToListen: String = "Ready to listen",
    val readyNote: String = "It’s in the library.",
    val stoppedMoving: String = "Stopped moving",
    val stoppedMovingNote: String = "The download stopped making progress.",
    val couldntAdd: String = "Couldn’t add it",
    val couldntAddNote: String = "It downloaded but couldn’t be added to the library.",
    val couldntFind: String = "Couldn’t find it",
    val couldntFindNote: String = "Nothing worth showing turned up.",
    val cancelled: String = "Cancelled",
    val cancelledNote: String = "This request was cancelled.",
    val ebook: String = "Ebook",
    val audiobook: String = "Audiobook",
    // The stepper and the search
    val ready: String = "Ready",
    val choseAVersion: String = "Chose a version",
    val lookingFound: (Int) -> String = { "Looking · $it found" },
    val lookingLabel: String = "Looking for versions…",
    val lookingSlowLabel: String = "Still searching for versions…",
    // Versions
    val formatUnknown: String = "Format unknown",
    val sizeUnknown: String = "Size unknown",
    val unknown: String = "Unknown",
    val usenet: String = "Usenet",
    val seeds: (count: String, n: Long) -> String = { count, n -> "$count seed${if (n == 1L) "" else "s"}" },
    val versionsFound: (Int) -> String = { "$it version${if (it == 1) "" else "s"} found" },
    val bestMatchFirst: String = "Best match first",
    val coverSizes: (Int, Int, Int, Int) -> String = { w, h, cw, ch ->
        "Its cover is $w × $h. The existing one is $cw × $ch."
    },
    // Time
    val lessThanAMinute: String = "less than a minute left",
    val minutesLeft: (Int) -> String = { "about $it min left" },
    val hoursLeft: (Int) -> String = { "about $it hour${if (it == 1) "" else "s"} left" },
    val justNow: String = "just now",
    val minutesAgo: (Long) -> String = { "${it}m ago" },
    val hoursAgo: (Long) -> String = { "${it}h ago" },
    val yesterday: String = "yesterday",
    val daysAgo: (Long) -> String = { "${it}d ago" },
    // Who and when
    val you: String = "You",
    val your: String = "your",
    val possessive: (String) -> String = { "$it’s" },
    val onWishlist: (String) -> String = { "On $it wishlist" },
    val onWishlists: (String, String) -> String = { others, last -> "On $others and $last wishlists" },
    val cancelledByYou: String = "Cancelled by you",
    val cancelledBy: (String) -> String = { "Cancelled by $it" },
    val historyLine: (kind: String, head: String, day: String) -> String = { kind, head, day -> "$kind $head · $day" },
    val stoppedAt: (Int) -> String = { "stopped at $it%" },
    val swappedForAnother: String = "Swapped for another version",
    // Failures
    val stillStarting: String = "Still starting the last request.",
    val tooManyRequests: String = "You have a lot of requests going. Try again in a few minutes.",
    val cantRequest: String = "Your account can’t make requests.",
    val bookGone: String = "That book is no longer in the library.",
    val couldntStart: String = "Couldn’t start the request.",
    val failureChoose: String = "Couldn’t choose that version",
    val failureCancel: String = "Couldn’t cancel",
    val failureUndo: String = "Couldn’t undo",
    val failureSwap: String = "Couldn’t choose another",
    val failureRetry: String = "Couldn’t try again",
    val failureTakeCover: String = "Couldn’t use that cover",
    val failureKeepCover: String = "Couldn’t keep this one",
    val requestCancelled: (kind: String) -> String = { "$it request cancelled" },
    val somethingWentWrong: String = "Something went wrong.",
    val serverError: (Int) -> String = { "Server error ($it)." },
    val failureLine: (prefix: String, message: String) -> String = { prefix, message -> "$prefix: $message" },
    // The Requests list
    val groupNeedsYou: String = "Needs you",
    val groupOnItsWay: String = "On its way",
    val groupLooking: String = "Looking",
    val groupStuck: String = "Stuck",
    val groupReady: String = "Ready",
    val groupCancelled: String = "Cancelled",
    val chooseAVersion: String = "choose a version",
    val choosingAVersion: String = "choosing a version",
    val lookingForAVersion: String = "looking for a version",
    val onItsWayLower: String = "on its way",
    val readyToReadLower: String = "ready to read",
    val readyToListenLower: String = "ready to listen",
    val cancelledLower: String = "cancelled",
    val itemLine: (kind: String, where: String) -> String = { kind, where -> "$kind · $where" },
    val books: (Int) -> String = { "$it book${if (it == 1) "" else "s"}" },
    val needsYou: (Int) -> String = { "$it ${if (it == 1) "needs" else "need"} you" },
    val countsLine: (books: String, needsYou: String?) -> String = { books, needs -> if (needs == null) books else "$books · $needs" },
)
